"""
Ответы на служебные фразы без обращения к LLM: «привет», «что ты умеешь?», «начнём заново».

Так пользователю, у которого нет меню команд, не нужно знать никаких команд, а токены на
такие вопросы не тратятся. Срабатывает только на короткие сообщения, чтобы не перехватывать
настоящие вопросы про пиво.
"""

import re
from typing import Optional

GREETING, HELP, RESET = "greeting", "help", "reset"

CAPABILITIES = (
    "Я Beer Style Assistant — справочник по пивным стилям BJCP 2021. "
    "Отвечаю по-русски и только по своей базе знаний: то, чего в ней нет, не выдумываю.\n\n"
    "Что можно спросить:\n"
    "• про стиль: «Какая горечь у American IPA?»\n"
    "• сравнить стили: «Чем отличается портер от стаута?»\n"
    "• найти подходящий: «Какое пиво светлое и лёгкое, вроде Bud Light?»\n"
    "• уточнить: «А какой у него цвет?» — я помню несколько последних вопросов\n\n"
    "Чего я не умею: отвечать не про пиво, подбирать сочетания с едой, "
    "искать конкретные марки и понимать фотографии. "
    "База знаний пока на английском, ответы я перевожу на лету, поэтому в переводе возможны неточности.\n\n"
    "Чтобы сменить тему, напиши «начнём заново»."
)

GREETING_REPLY = "Привет! 🍺 " + CAPABILITIES
RESET_REPLY = "Хорошо, забыл предыдущий разговор. О каком пивном стиле поговорим?"

MAX_WORDS = 8

_RESET = re.compile(
    r"^(забудь( все| разговор| диалог)?|начн[иеё]м? (все )?заново|начни сначала|"
    r"очисти(ть)? (историю|диалог)|сбрось( диалог| историю)?)$"
)
_GREETING = re.compile(
    r"^(привет(ствую)?|здравствуй(те)?|добрый (день|вечер)|доброе утро|хай|здорово|салют|hello|hi)( бот)?$"
)
_HELP = re.compile(
    r"(что (ты )?умеешь|что (ты )?можешь|чем (ты )?(можешь )?помо(чь|жешь)|"
    r"как (тобой |ботом |этим ботом )?пользоваться|расскажи о себе|кто ты|ты кто|"
    r"что это за бот|что ты за бот|что ты такое|для чего ты|зачем ты нужен)|"
    r"^(помощь|справка|help|команды|что делать)$"
)


def _normalize(text: str) -> str:
    text = text.lower().replace("ё", "е")
    text = re.sub(r"[^\w\s]", " ", text)  # пунктуация и эмодзи
    return re.sub(r"\s+", " ", text).strip()


def detect(text: str) -> Optional[str]:
    """GREETING, HELP, RESET или None, если это обычный вопрос."""
    norm = _normalize(text)
    if not norm or len(norm.split()) > MAX_WORDS:
        return None
    if _RESET.match(norm.replace("ё", "е")):
        return RESET
    if _GREETING.match(norm):
        return GREETING
    if _HELP.search(norm):
        return HELP
    return None
